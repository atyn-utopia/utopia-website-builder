// ── Derived stats ──────────────────────────────────────────────────────────
export type Band = 'mature' | 'partial' | 'gap'

export function band(maturity: number): Band {
  if (maturity >= 75) return 'mature'
  if (maturity >= 45) return 'partial'
  return 'gap'
}

export const ALL_UNITS = LAYERS.flatMap((l) => l.units)

export const STATS = {
  totalUnits: ALL_UNITS.length,
  totalLayers: LAYERS.length,
  avg: Math.round(
    ALL_UNITS.reduce((s, u) => s + u.maturity, 0) / ALL_UNITS.length,
  ),
  mature: ALL_UNITS.filter((u) => band(u.maturity) === 'mature').length,
  partial: ALL_UNITS.filter((u) => band(u.maturity) === 'partial').length,
  gap: ALL_UNITS.filter((u) => band(u.maturity) === 'gap').length,
}

export function layerAvg(layer: Layer): number {
  return Math.round(
    layer.units.reduce((s, u) => s + u.maturity, 0) / layer.units.length,
  )
}

