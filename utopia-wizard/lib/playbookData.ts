// ─────────────────────────────────────────────────────────────────────────
// Build Playbook — the website-builder system decomposed into layers + units.
//
// Grounded in CLAUDE.md, docs/website-building-flow.md, docs/full-website-setup.md
// and the agent definitions in agents/. Each unit carries a maturity score, an
// owning agent, a 12-field spec, and links to the source markdown so the
// playbook stays traceable to the repo.
//
// Maturity bands:  🟢 mature ≥ 75   🟡 partial 45–74   🔴 gap < 45
// ─────────────────────────────────────────────────────────────────────────

export const GH_BASE =
  'https://github.com/atyn-utopia/utopia-website-builder/blob/main/'

export interface DocLink {
  label: string
  path: string // repo-relative; resolved against GH_BASE
}

export interface UnitSpec {
  purpose: string
  scope: string
  triggers: string
  inputs: string
  steps: string
  outputs: string
  variants: string
  guardrails: string
  integrations: string
  completion: string
  examples: string
  openItems: string
}

export interface Unit {
  name: string
  owner: string
  ownerPath: string // agent md
  maturity: number // 0–100
  spec: UnitSpec
  docs: DocLink[]
}

export interface Layer {
  id: number
  name: string
  subtitle: string
  phase: 'BUILD' | 'DATA' | 'SHIP'
  units: Unit[]
}

